const controlStyle = {
  border: '1px solid #d1d5db',
  borderRadius: 8,
  background: '#fff',
  overflow: 'hidden',
} as const

/** Visual selector for every CMS icon field. Stored value is the semantic icon key. */
export default function IconPicker({ value, onChange, forID, classNameWrapper, isDisabled }: CmsWidgetControlProps<string>) {
  const [query, setQuery] = useState('')
  const selected = typeof value === 'string' ? value : ''
  const normalizedQuery = query.trim().toLocaleLowerCase('es')
  const options = useMemo(
    () =>
      ICON_OPTIONS.filter(({ name, label }) => {
        const searchable = `${name} ${label}`.toLocaleLowerCase('es')
        return searchable.includes(normalizedQuery)
      }),
    [normalizedQuery]
  )

  return (
    <div className={classNameWrapper} style={controlStyle}>
      <label htmlFor={`${forID}-search`} style={{ display: 'flex', alignItems: 'center', gap: 8, padding: '10px 12px', borderBottom: '1px solid #e5e7eb' }}>
        <Search size={16} color="#6b7280" aria-hidden="true" />
        <input
          id={`${forID}-search`}
          type="search"
          value={query}
          onChange={(event) => setQuery(event.target.value)}
          placeholder="Buscar icono: terapia, familia, calendario..."
          disabled={isDisabled}
          style={{ border: 0, outline: 'none', width: '100%', fontSize: 14, color: '#1f2937' }}
        />
      </label>

      <div aria-label="Opciones de iconos Lucide" role="listbox" style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(92px, 1fr))', gap: 6, maxHeight: 260, overflowY: 'auto', padding: 10 }}>
        {options.map((option) => {
          const LucideIcon = ICON_COMPONENTS[option.lucideName]
          const isSelected = selected === option.name
          return (
            <button
              key={option.name}
              type="button"
              role="option"
              aria-selected={isSelected}
              aria-label={`Usar icono ${option.label}`}
              onClick={() => onChange(option.name)}
              disabled={isDisabled}
              title={option.label}
              style={{
                position: 'relative',
                display: 'flex',
                minHeight: 76,
                flexDirection: 'column',
                alignItems: 'center',
                justifyContent: 'center',
                gap: 5,
                padding: 8,
                border: isSelected ? '2px solid #229cc2' : '1px solid #e5e7eb',
                borderRadius: 8,
                background: isSelected ? '#e8f7fb' : '#fff',
                color: isSelected ? '#157a9a' : '#374151',
                cursor: isDisabled ? 'not-allowed' : 'pointer',
              }}
            >
              <LucideIcon size={22} strokeWidth={1.8} aria-hidden="true" />
              <span style={{ fontSize: 11, lineHeight: 1.1, textAlign: 'center' }}>{option.label}</span>
              {isSelected && <Check size={13} strokeWidth={3} aria-hidden="true" style={{ position: 'absolute', top: 5, right: 5 }} />}
            </button>
          )
        })}
      </div>

      {options.length === 0 && <p style={{ margin: 0, padding: '12px', color: '#6b7280', fontSize: 13 }}>No hay iconos que coincidan con la búsqueda.</p>}
      <div style={{ padding: '8px 12px', borderTop: '1px solid #e5e7eb', color: '#6b7280', fontSize: 12 }}>
        Seleccionado: <strong style={{ color: '#374151' }}>{selected || 'ninguno'}</strong>
      </div>
    </div>
  )
}
